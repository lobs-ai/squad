const FORCE = argv.includes("--force") || argv.includes("-f");
const NON_INTERACTIVE = argv.includes("--yes") || argv.includes("-y");

const rl = createInterface({ input: stdin, output: stdout });

function bold(s) {
  return `\x1b[1m${s}\x1b[0m`;
}
function dim(s) {
  return `\x1b[2m${s}\x1b[0m`;
}
function green(s) {
  return `\x1b[32m${s}\x1b[0m`;
}
function yellow(s) {
  return `\x1b[33m${s}\x1b[0m`;
}
function red(s) {
  return `\x1b[31m${s}\x1b[0m`;
}
function cyan(s) {
  return `\x1b[36m${s}\x1b[0m`;
}

/**
 * Step header. Printed before each section so the user can see progress and
 * whether the section is required or optional.
 */
function stepHeader(n, total, title, required) {
  const tag = required ? green("required") : dim("optional");
  console.log(
    `\n${cyan(`── Step ${n}/${total}`)} ${bold(title)}  ${tag}`,
  );
}

/**
 * Single-select picker with ↑/↓ navigation. Returns the chosen option label.
 * Falls back to `options[defaultIdx]` when non-TTY or NON_INTERACTIVE.
 *
 * Zero-deps on purpose — this script runs before `pnpm install`, so we can't
 * rely on enquirer/inquirer/prompts.
 */
async function pickOne(title, options, defaultIdx = 0) {
  if (NON_INTERACTIVE || !stdin.isTTY) {
    return options[Math.max(0, Math.min(defaultIdx, options.length - 1))];
  }
  rl.pause();
  stdin.setRawMode(true);
  stdin.resume();

  let cursor = Math.max(0, Math.min(defaultIdx, options.length - 1));
  const totalLines = options.length + 2; // title + hint + rows

  const paint = (first) => {
    if (!first) process.stdout.write(`\x1b[${totalLines}A`);
    process.stdout.write(`${title}\x1b[K\n`);
    process.stdout.write(dim("  ↑/↓ to move, enter to select") + "\x1b[K\n");
    for (let i = 0; i < options.length; i++) {
      const marker = i === cursor ? cyan("❯") : " ";
      const label = i === cursor ? bold(options[i]) : options[i];
      process.stdout.write(`${marker} ${label}\x1b[K\n`);
    }
  };
  paint(true);

  return new Promise((resolveP) => {
    const onData = (buf) => {
      const s = buf.toString();
      if (s === "\r" || s === "\n") {
        stdin.removeListener("data", onData);
        stdin.setRawMode(false);
        stdin.pause();
        rl.resume();
        resolveP(options[cursor]);
      } else if (s === "\x03") {
        stdin.setRawMode(false);
        process.exit(130);
      } else if (s === "\x1b[A" || s === "k") {
        cursor = (cursor - 1 + options.length) % options.length;
        paint(false);
      } else if (s === "\x1b[B" || s === "j") {
        cursor = (cursor + 1) % options.length;
        paint(false);
      }
    };
    stdin.on("data", onData);
  });
}

/**
 * Multi-select picker. Space toggles the current row, `a` toggles all, enter
 * confirms. Returns a Set of chosen indices (0-based). Falls back to the
 * preselected set in non-TTY mode.
 */
async function pickMany(title, options, preselected = new Set()) {
  if (NON_INTERACTIVE || !stdin.isTTY) {
    return new Set(preselected);
  }
  rl.pause();
  stdin.setRawMode(true);
  stdin.resume();

  let cursor = 0;
  const selected = new Set(preselected);
  const totalLines = options.length + 2;

  const paint = (first) => {
    if (!first) process.stdout.write(`\x1b[${totalLines}A`);
    process.stdout.write(`${title}\x1b[K\n`);
    process.stdout.write(
      dim("  ↑/↓ to move, space to toggle, a to toggle all, enter to confirm") +
        "\x1b[K\n",
    );
    for (let i = 0; i < options.length; i++) {
      const cur = i === cursor ? cyan("❯") : " ";
      const mark = selected.has(i) ? green("◉") : dim("◯");
      const label = i === cursor ? bold(options[i]) : options[i];
      process.stdout.write(`${cur} ${mark} ${label}\x1b[K\n`);
    }
  };
  paint(true);

  return new Promise((resolveP) => {
    const onData = (buf) => {
      const s = buf.toString();
      if (s === "\r" || s === "\n") {
        stdin.removeListener("data", onData);
        stdin.setRawMode(false);
        stdin.pause();
        rl.resume();
        resolveP(selected);
      } else if (s === "\x03") {
        stdin.setRawMode(false);
        process.exit(130);
      } else if (s === "\x1b[A" || s === "k") {
        cursor = (cursor - 1 + options.length) % options.length;
        paint(false);
      } else if (s === "\x1b[B" || s === "j") {
        cursor = (cursor + 1) % options.length;
        paint(false);
      } else if (s === " ") {
        if (selected.has(cursor)) selected.delete(cursor);
        else selected.add(cursor);
        paint(false);
      } else if (s === "a" || s === "A") {
        if (selected.size === options.length) selected.clear();
        else for (let i = 0; i < options.length; i++) selected.add(i);
        paint(false);
      }
    };
    stdin.on("data", onData);
  });
}

/**
 * Ask whether to skip an optional step. Returns `true` for skip. Honors a
 * `previouslyConfigured` hint so re-runs default to "keep configuring it".
 */
async function skipPrompt(previouslyConfigured) {
  if (NON_INTERACTIVE) return !previouslyConfigured;
  const defSkip = !previouslyConfigured;
  const suffix = defSkip ? "[Y/n]" : "[y/N]";
  while (true) {
    const raw = (await rl.question(`  Skip this step? ${suffix} `)).trim().toLowerCase();
    if (!raw) return defSkip;
    if (["y", "yes", "s", "skip"].includes(raw)) return true;
    if (["n", "no"].includes(raw)) return false;
    console.log(red("  please answer yes or no"));
  }
}

async function ask(prompt, { default: def, secret = false } = {}) {
  if (NON_INTERACTIVE) return def ?? "";
  const suffix = def ? dim(` [${secret ? mask(def) : def}]`) : "";
  const answer = (await rl.question(`${prompt}${suffix} `)).trim();
  return answer || def || "";
}

async function askChoice(prompt, choices, def) {
  if (NON_INTERACTIVE) return def;
  const labels = choices
    .map((c, i) => `${i + 1}) ${c}${c === def ? dim(" (default)") : ""}`)
    .join("  ");
  while (true) {
    const raw = (await rl.question(`${prompt}\n  ${labels}\n> `)).trim();
    if (!raw) return def;
    const n = Number(raw);
    if (Number.isInteger(n) && n >= 1 && n <= choices.length) return choices[n - 1];
    if (choices.includes(raw)) return raw;
    console.log(red("  pick a number from the list above"));
  }
}

async function askYesNo(prompt, def = false) {
  if (NON_INTERACTIVE) return def;
  const suffix = def ? "[Y/n]" : "[y/N]";
  while (true) {
    const raw = (await rl.question(`${prompt} ${suffix} `)).trim().toLowerCase();
    if (!raw) return def;
    if (["y", "yes"].includes(raw)) return true;
    if (["n", "no"].includes(raw)) return false;
    console.log(red("  please answer yes or no"));
  }
}

function mask(secret) {
  if (!secret) return "";
  if (secret.length <= 8) return "***";
  return `${secret.slice(0, 4)}…${secret.slice(-4)}`;
}

function generateToken(bytes = 32) {
  return randomBytes(bytes).toString("base64url");
}

/**
 * Read a git config value from the host (best-effort, used to pre-fill the
 * committer name/email prompts). Returns "" if git is absent or unset.
 */
function detectGitHost(key) {
  try {
    return execSync(`git config --global --get ${key}`, {
      stdio: ["ignore", "pipe", "ignore"],
      encoding: "utf8",
    }).trim();
  } catch {
    return "";
  }
}

function ghInstalled() {
  try {
    execSync("gh --version", { stdio: ["ignore", "ignore", "ignore"] });
    return true;
  } catch {
    return false;
  }
}

/**
 * Squad keeps its own gh config sandbox under docker/data/gh/ so signing in
 * for the squad container doesn't overwrite the user's personal `gh auth` on
 * the host.
 */
const SQUAD_GH_DIR = join(DATA_DIR, "gh");

function ghEnv(configDir) {
  // Strip GITHUB_TOKEN / GH_TOKEN from the inherited env when calling gh —
  // otherwise gh sees the host's token and refuses to start the login flow.
  const e = { ...env };
  delete e.GITHUB_TOKEN;
  delete e.GH_TOKEN;
  if (configDir) e.GH_CONFIG_DIR = configDir;
  return e;
}

function detectGhToken(configDir) {
  try {
    return execSync("gh auth token", {
      stdio: ["ignore", "pipe", "ignore"],
      encoding: "utf8",
      env: ghEnv(configDir),
    }).trim();
  } catch {
    return "";
  }
}

function detectGhUser(configDir) {
  try {
    return execSync("gh api user --jq .login", {
      stdio: ["ignore", "pipe", "ignore"],
      encoding: "utf8",
      env: ghEnv(configDir),
    }).trim();
  } catch {
    return "";
  }
}

/**
 * Drive `gh auth login` against the squad-only sandbox dir. The host's
 * personal gh auth is left untouched. Returns { token, user }.
 */
function runGhAuthLoginSandboxed() {
  mkdirSync(SQUAD_GH_DIR, { recursive: true });
  try {
    execSync(
      "gh auth login --hostname github.com --git-protocol https --web",
      { stdio: "inherit", env: ghEnv(SQUAD_GH_DIR) },
    );
  } catch {
    return { token: "", user: "" };
  }
  return {
    token: detectGhToken(SQUAD_GH_DIR),
    user: detectGhUser(SQUAD_GH_DIR),
  };
}

// Minimal .env parser — KEY=VALUE per line, ignores comments and blanks.
function parseEnv(text) {
  const out = {};
  for (const rawLine of text.split(/\r?\n/)) {
    const line = rawLine.trim();
    if (!line || line.startsWith("#")) continue;
    const eq = line.indexOf("=");
    if (eq < 0) continue;
    const key = line.slice(0, eq).trim();
    let val = line.slice(eq + 1).trim();
    if ((val.startsWith('"') && val.endsWith('"')) || (val.startsWith("'") && val.endsWith("'"))) {
      val = val.slice(1, -1);
    }
    out[key] = val;
  }
  return out;
}

function loadEnvFile(path) {
  if (!existsSync(path)) return {};
  return parseEnv(readFileSync(path, "utf8"));
}

/**
 * Read or initialize ~/.squad/squads.json. Same shape as packages/client-cli's
 * Registry — duplicated here so setup.mjs has no dependencies (it runs before
 * `pnpm install`).
 */
function loadRegistry() {
  if (!existsSync(REGISTRY_PATH)) {
    return { build_context: REPO_ROOT, squads: [], shared: { searxng_port: 8888 } };
  }
  try {
    const parsed = JSON.parse(readFileSync(REGISTRY_PATH, "utf8"));
    return {
      build_context: parsed.build_context || REPO_ROOT,
      squads: Array.isArray(parsed.squads) ? parsed.squads : [],
      shared: { searxng_port: 8888, ...(parsed.shared ?? {}) },
    };
  } catch {
    return { build_context: REPO_ROOT, squads: [], shared: { searxng_port: 8888 } };
  }
}

function saveRegistry(reg) {
  mkdirSync(SQUAD_HOME, { recursive: true });
  writeFileSync(REGISTRY_PATH, JSON.stringify(reg, null, 2) + "\n");
}

function findFreeHostPort(reg, start = 8080) {
  const taken = new Set(reg.squads.map((s) => s.port));
  taken.add(reg.shared.searxng_port);
  let p = start;
  while (taken.has(p)) p++;
  return p;
}

/**
 * Insert/update this squad's entry in the registry, then regenerate
 * ~/.squad/docker-compose.yml. The compose generator lives in the built
 * client-cli; if dist isn't present, print a hint and continue (the user can
 * run `squad mgr regen` after building).
 */
function syncRegistryAndCompose(hostPort) {
  const reg = loadRegistry();
  const existing = reg.squads.find((s) => s.name === SQUAD_NAME);
  if (existing) {
    if (hostPort) existing.port = hostPort;
  } else {
    const port = hostPort ?? findFreeHostPort(reg);
    reg.squads.push({ name: SQUAD_NAME, port });
  }
  reg.build_context = REPO_ROOT;
  saveRegistry(reg);

  // Pin the just-configured squad as current so `squad chat` etc. target it
  // without --squad. Idempotent.
  mkdirSync(SQUAD_HOME, { recursive: true });
  writeFileSync(CURRENT_FILE, SQUAD_NAME + "\n");

  // Trigger compose regen via the built CLI. Falls back to a hint when dist
  // isn't built yet (first-time install).
  const cliBin = join(REPO_ROOT, "packages", "client-cli", "dist", "cli.js");
  if (existsSync(cliBin)) {
    try {
      execSync(`node ${JSON.stringify(cliBin)} mgr regen`, { stdio: "inherit" });
    } catch {
      console.log(yellow("  (compose regen failed — run 'squad mgr regen' once squad is built)"));
    }
  } else {
    console.log(
      dim(
        `  (skipping compose regen — packages/client-cli/dist not built yet. Run 'pnpm build && squad mgr regen'.)`,
      ),
    );
  }
}


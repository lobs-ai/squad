#!/usr/bin/env node
// Interactive Squad setup wizard.
//
// Walks the user through the minimum config + secrets needed to launch the
// gateway, then writes them to ~/.squad/squads/<name>/{config.json,.env}.
// The bind mount target inside each container is /app/docker/, so the
// generated config keeps using that as its data_dir.
//
// Pass --squad <name> to set up a specific squad. Defaults to 'default'.
//
// Re-runnable: detects existing files and offers to keep, overwrite, or merge
// individual values. No external deps so it works before `pnpm install`.

import { existsSync, mkdirSync, readFileSync, writeFileSync, chmodSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { createInterface } from "node:readline/promises";
import { stdin, stdout, argv, env, exit } from "node:process";
import { randomBytes } from "node:crypto";
import { execSync } from "node:child_process";
import { homedir } from "node:os";

const SCRIPT_DIR = dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = resolve(SCRIPT_DIR, "..");

// Pick the squad to set up: --squad <name>, else 'default'.
function getFlagValue(name) {
  const i = argv.indexOf(name);
  if (i === -1 || i + 1 >= argv.length) return undefined;
  return argv[i + 1];
}
const SQUAD_NAME = getFlagValue("--squad") || "default";
if (!/^[a-z0-9][a-z0-9_-]{0,30}$/.test(SQUAD_NAME)) {
  console.error(`invalid squad name '${SQUAD_NAME}': lowercase alnum/_/-, ≤31 chars.`);
  exit(2);
}

